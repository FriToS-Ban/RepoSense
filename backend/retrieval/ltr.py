"""Learned fusion: a linear (logistic) reranker over the union of channel candidates (design §5.4, ADR-11; M9).

RRF only sees ranks.  On T2 it lets low-precision graph items displace good lexical ones
(M4, M5).  The reranker instead scores every candidate from evidence that is comparable
across channels:

  lexical     normalised BM25F score, reciprocal lexical rank, generated by the lexical
              channel, the candidate's name occurs on a changed line
  structural  1-hop relation to a seed (one-hot), relation score, reciprocal PPR rank,
              log PPR mass, reachable in two typed hops
  co-change   coupling confidence of the candidate's file with a changed file, log support
  node        test / method / class, private name, log size, log in-degree, same directory
              as a changed file, same top-level package

Pointwise logistic regression with L2, fitted by Newton's method (IRLS) on standardised
features; a few dozen lines, no dependency.  Weights are reported for interpretability.
Feature groups can be masked to measure what each kind of evidence contributes.
"""
from __future__ import annotations

import json
import math
import random
from dataclasses import dataclass, field
from pathlib import Path

REL = ("callee_on_changed_line", "callee", "caller", "override", "overridden", "tests", "tested", "parent")
GROUPS = {
    "lexical": ("lex_score", "lex_rrank", "lex_gen", "name_on_changed_line"),
    "graph": tuple(f"rel_{r}" for r in REL) + ("struct_score", "ppr_rrank", "ppr_log", "two_hop"),
    "cochange": ("cc_conf", "cc_support_log"),
    "node": ("is_test", "is_method", "is_class", "is_private", "size_log", "fanin_log", "same_dir", "same_top"),
}
FEATURES = tuple(f for g in ("lexical", "graph", "cochange", "node") for f in GROUPS[g])


def _test_path(path: str) -> bool:
    parts = path.split("/")
    return any(p in ("tests", "test", "testing") for p in parts[:-1]) or parts[-1].startswith("test_") \
        or parts[-1].endswith("_test.py") or parts[-1] == "conftest.py"


def _generator(label: str) -> str:
    if label == "structural:ppr":
        return "ppr"
    return label.split(":", 1)[0]


def candidate_features(retr, change, pr_text: str, cfg, overlay=None, cochange=None, cochange_support=None,
                       generators=None):
    """[(snapshot index, {feature: value}, channel label)] for the union of the lexical, structural
    (1-hop), PPR and co-change candidate lists of one change.  ``overlay``: the seeds' HEAD-side
    dependencies (RepoRetriever._overlay_out); ``cochange``: path -> [(path, confidence)];
    ``cochange_support``: (path, path) -> number of commits changing both; ``generators``: keep only
    candidates generated by these channels (lexical, structural, ppr, cochange; None = all)."""
    from backend.kg.model import EdgeType, Kind
    from backend.retrieval.lexical import tokenize
    from backend.retrieval.ppr import Transitions, typed_bfs, ppr_push, sources_from_seeds
    from backend.retrieval.structural import expand

    snap = retr.snap
    exclude = {i for p in change.changed_paths for i in snap.symbols_in(p)}
    exclude |= {sd.index for sd in change.seeds if sd.index is not None}
    seed_idx = {sd.index for sd in change.seeds if sd.index is not None}
    labels: dict[int, set[str]] = {}

    lex = retr._lexical_candidates(change.seeds, exclude, pr_text, cfg)
    lex_rank = {i: r for r, (i, _s, _l) in enumerate(lex, 1)}
    q: dict[str, float] = {}
    for sd in change.seeds:
        for t, w in retr._seed_query(sd, pr_text, cfg).items():
            q[t] = max(q.get(t, 0.0), w)
    lex_all = dict(retr.lexical.search(q, 5000, exclude, cfg.bm25f_weights, cfg.bm25_k1, cfg.bm25_b)) if q else {}
    top = max(lex_all.values(), default=1.0) or 1.0
    for i, _s, _l in lex:
        labels.setdefault(i, set()).add("lexical")

    st = expand(snap, change.seeds, cfg.structural_limit, use_plan=cfg.use_plan, overlay_out=overlay)
    st_info = {i: (sc, lab.split(":", 1)[1]) for i, sc, lab in st}
    for i, _sc, lab in st:
        labels.setdefault(i, set()).add(lab)
    if retr._trans is None:
        retr._trans = Transitions(snap)
    src = sources_from_seeds(snap, change.seeds, overlay)
    ppr = ppr_push(retr._trans, src, cfg.ppr_alpha, cfg.ppr_eps) if src else {}
    ppr_sorted = sorted((v for v in ppr if v not in seed_idx and snap.symbols[v].kind != Kind.MODULE),
                        key=lambda v: (-ppr[v], v))
    ppr_rank = {v: r for r, v in enumerate(ppr_sorted, 1)}
    for v in ppr_sorted[: cfg.structural_limit]:
        labels.setdefault(v, set()).add("structural:ppr")
    two = {v for v, (_s, h, _p) in typed_bfs(retr._trans, src, 2).items() if h == 2} if src else set()

    cc_file: dict[str, float] = {}
    if cochange is not None:
        for p in sorted(change.changed_paths):
            for other, conf in cochange(p)[: cfg.cochange_files]:
                if other not in change.changed_paths:
                    cc_file[other] = max(cc_file.get(other, 0.0), conf)
        for i, _s, _l in retr._cochange_candidates(change, exclude, pr_text, cochange, cfg):
            labels.setdefault(i, set()).add("cochange")

    changed_tokens = set()
    for sd in change.seeds:
        for text, w in sd.query_lines:
            if w >= 1.0:
                changed_tokens.update(tokenize(text))
    dirs = {p.rsplit("/", 1)[0] if "/" in p else "" for p in change.changed_paths}
    tops = {p.split("/", 1)[0] for p in change.changed_paths}

    allowed = set(generators) if generators is not None else None
    out = []
    for i in sorted(labels):
        if i in exclude or snap.symbols[i].kind == Kind.MODULE:
            continue
        if allowed is not None and not allowed & {_generator(lab) for lab in labels[i]}:
            continue
        s = snap.symbols[i]
        f = dict.fromkeys(FEATURES, 0.0)
        f["lex_score"] = lex_all.get(i, 0.0) / top
        f["lex_rrank"] = 1.0 / lex_rank[i] if i in lex_rank else 0.0
        f["lex_gen"] = float(i in lex_rank)
        f["name_on_changed_line"] = float(s.name.lower() in changed_tokens)
        if i in st_info:
            sc, rel = st_info[i]
            f["struct_score"] = sc
            if f"rel_{rel}" in f:
                f[f"rel_{rel}"] = 1.0
        f["ppr_rrank"] = 1.0 / ppr_rank[i] if i in ppr_rank else 0.0
        f["ppr_log"] = (math.log10(ppr[i]) + 9.0) / 9.0 if ppr.get(i, 0.0) > 1e-9 else 0.0
        f["two_hop"] = float(i in two)
        f["cc_conf"] = cc_file.get(s.path, 0.0)
        if cochange_support is not None and s.path in cc_file:
            f["cc_support_log"] = math.log1p(max((cochange_support(p, s.path) for p in change.changed_paths), default=0))
        f["is_test"] = float(_test_path(s.path))
        f["is_method"] = float(s.kind == Kind.METHOD)
        f["is_class"] = float(s.kind == Kind.CLASS)
        f["is_private"] = float(s.name.startswith("_") and not s.name.startswith("__"))
        f["size_log"] = math.log1p(s.end_line - s.start_line + 1)
        f["fanin_log"] = math.log1p(sum(len(snap.neighbors(i, t, "in")) for t in (EdgeType.CALLS, EdgeType.REFERENCES)))
        f["same_dir"] = float((s.path.rsplit("/", 1)[0] if "/" in s.path else "") in dirs)
        f["same_top"] = float(s.path.split("/", 1)[0] in tops)
        out.append((i, f, "+".join(sorted(labels[i]))))
    return out


@dataclass
class LinearRanker:
    features: tuple
    weights: list
    bias: float
    mean: list
    std: list
    meta: dict = field(default_factory=dict)

    def score(self, f: dict) -> float:
        z = self.bias
        for k, w, m, s in zip(self.features, self.weights, self.mean, self.std):
            z += w * (f.get(k, 0.0) - m) / s
        return z

    def to_json(self) -> str:
        return json.dumps({"features": list(self.features), "weights": self.weights, "bias": self.bias,
                           "mean": self.mean, "std": self.std, "meta": self.meta}, indent=1, sort_keys=True)

    @classmethod
    def load(cls, path: str | Path) -> "LinearRanker":
        d = json.loads(Path(path).read_text(encoding="utf-8"))
        return cls(tuple(d["features"]), d["weights"], d["bias"], d["mean"], d["std"], d.get("meta", {}))


def _solve(a: list[list[float]], b: list[float]) -> list[float]:
    """Gaussian elimination with partial pivoting (small dense systems)."""
    n = len(b)
    m = [row[:] + [b[i]] for i, row in enumerate(a)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(m[r][c]))
        m[c], m[p] = m[p], m[c]
        piv = m[c][c] or 1e-12
        for r in range(c + 1, n):
            k = m[r][c] / piv
            if k:
                for j in range(c, n + 1):
                    m[r][j] -= k * m[c][j]
    x = [0.0] * n
    for r in range(n - 1, -1, -1):
        x[r] = (m[r][n] - sum(m[r][j] * x[j] for j in range(r + 1, n))) / (m[r][r] or 1e-12)
    return x


def fit(rows: list[tuple[dict, int]], features=FEATURES, l2: float = 1.0, iters: int = 25,
        neg_per_pos: int | None = None, seed: int = 0) -> LinearRanker:
    """L2-regularised logistic regression by IRLS.  ``neg_per_pos`` subsamples negatives (seeded);
    uniform negative subsampling shifts only the intercept, not the ranking."""
    if neg_per_pos is not None:
        pos = [r for r in rows if r[1]]
        neg = [r for r in rows if not r[1]]
        random.Random(seed).shuffle(neg)
        rows = pos + neg[: neg_per_pos * max(1, len(pos))]
    feats = list(features)
    n, d = len(rows), len(feats)
    mean = [sum(r[0].get(f, 0.0) for r in rows) / n for f in feats]
    std = [math.sqrt(sum((r[0].get(f, 0.0) - mu) ** 2 for r in rows) / n) or 1.0 for f, mu in zip(feats, mean)]
    X = [[1.0] + [(r[0].get(f, 0.0) - mu) / sd for f, mu, sd in zip(feats, mean, std)] for r in rows]
    y = [float(r[1]) for r in rows]
    w = [0.0] * (d + 1)
    for _ in range(iters):
        g = [0.0] * (d + 1)
        h = [[0.0] * (d + 1) for _ in range(d + 1)]
        for x, t in zip(X, y):
            z = sum(a * b for a, b in zip(w, x))
            p = 1.0 / (1.0 + math.exp(-z)) if z > -30 else 0.0
            e, v = p - t, p * (1.0 - p)
            for j in range(d + 1):
                g[j] += e * x[j]
                if v:
                    vx = v * x[j]
                    hj = h[j]
                    for k in range(j, d + 1):
                        hj[k] += vx * x[k]
        for j in range(1, d + 1):
            g[j] += l2 * w[j]
            h[j][j] += l2
        for j in range(d + 1):
            for k in range(j):
                h[j][k] = h[k][j]
        step = _solve(h, g)
        w = [a - b for a, b in zip(w, step)]
        if max(abs(s) for s in step) < 1e-6:
            break
    return LinearRanker(tuple(feats), w[1:], w[0], mean, std, {"rows": n, "positives": int(sum(y)), "l2": l2})
