"""M8: the dense channel on T2 (systems B = dense alone, AB = lexical + dense by RRF).

    DENSE_BASE_URL=https://integrate.api.nvidia.com/v1 DENSE_MODEL=nvidia/nv-embedcode-7b-v1 \
    DENSE_API_KEY=... python -m eval.run_t2_dense            # -> eval/results/t2-dense-<model>/

The backend is configured only through those environment variables (never read from .env
files) and the run refuses to start without them: it makes paid API calls.  Passages are
cached by (model, symbol content hash) in eval/.cache/dense/, so a symbol version that
appears in many snapshots is embedded once.  The run also counts the judged symbols that
only the dense channel generates (no lexical, structural, PPR or co-change candidate).

``--hashing`` runs the same harness with the offline feature-hashing stand-in.  That checks
the plumbing end to end; its numbers are NOT a dense-retrieval result.

Decision rule (design §9 M8): keep the dense channel only if AB beats A on T2 R@budget with
p < 0.01, or dense adds >= 5% unique relevant candidates (judged symbols that no other
channel generates) at acceptable cost.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from eval.run_t2 import evaluate

EVAL_DIR = Path(__file__).resolve().parent


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--hashing", action="store_true", help="offline plumbing check with the hashing stand-in")
    ap.add_argument("--repos", default="")
    ap.add_argument("--out", default="")
    args = ap.parse_args(argv)
    from backend.retrieval.dense import EmbeddingCache, HashingBackend, OpenAICompatibleBackend
    from backend.retrieval.pipeline import RetrievalConfig

    backend = HashingBackend(256) if args.hashing else OpenAICompatibleBackend.from_env()
    if backend is None:
        print("dense backend not configured: set DENSE_BASE_URL, DENSE_MODEL and DENSE_API_KEY (paid API calls)")
        return 2
    slug = re.sub(r"[^A-Za-z0-9]+", "-", backend.name).strip("-")
    cache = EmbeddingCache(EVAL_DIR / ".cache" / "dense" / f"{slug}.jsonl")
    out = Path(args.out) if args.out else EVAL_DIR / "results" / f"t2-dense-{slug}"
    systems = {"B": RetrievalConfig(channels=("dense",)), "AB": RetrievalConfig(channels=("lexical", "dense"))}
    unique = {"judged": 0, "dense": 0, "dense_only": 0}

    def prepare(ctx):
        from backend.retrieval.diff import parse_unified_diff
        from backend.retrieval.ppr import multihop_candidates
        from backend.retrieval.seeds import link
        from backend.retrieval.structural import expand

        retr, q = ctx.retr, ctx.q
        retr.attach_dense(backend, cache)
        cfg, snap = RetrievalConfig(), retr.snap
        change = link(snap, parse_unified_diff(ctx.diff), ctx.head)
        exclude = {i for p in change.changed_paths for i in snap.symbols_in(p)}
        exclude |= {sd.index for sd in change.seeds if sd.index is not None}
        key = lambda lst: {f"{snap.symbols[c[0]].path}::{snap.symbols[c[0]].qualname}" for c in lst}  # noqa: E731
        dense = key(retr._dense_candidates(change.seeds, exclude, q.message, cfg))
        others = key(retr._lexical_candidates(change.seeds, exclude, q.message, cfg))
        others |= key(expand(snap, change.seeds, cfg.structural_limit))
        others |= key(multihop_candidates(snap, change.seeds, "ppr", cfg.structural_limit))
        others |= key(retr._cochange_candidates(change, exclude, q.message, ctx.cochange.related, cfg))
        judged = set(q.grades("sym_all"))
        unique["judged"] += len(judged)
        unique["dense"] += len(judged & dense)
        unique["dense_only"] += len((judged & dense) - others)

    res = evaluate(["A", *systems], out, [r for r in args.repos.split(",") if r] or None, systems, prepare=prepare)
    print(f"judged symbols generated by dense: {unique['dense']}/{unique['judged']}; "
          f"by dense only: {unique['dense_only']} ({unique['dense_only'] / max(1, unique['judged']):.1%})")
    (out / "unique_candidates.json").write_text(__import__("json").dumps(unique, indent=1) + "\n", encoding="utf-8")
    for name in ("A", "B", "AB"):
        m = res["metrics"].get(f"commit|{name}|sym_all")
        if m:
            print(f"{name:3s} R@budget={m['R@all']:.3f} R@10={m['R@10']:.3f} nDCG@10={m['nDCG@10']:.3f}")
    print(f"wrote {out}; compare with: python -m eval.compare {out}:AB {out}:A --view sym_all")
    return 0


if __name__ == "__main__":
    sys.exit(main())
